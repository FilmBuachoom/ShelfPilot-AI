#!/usr/bin/env python3
"""Generate the GitHub Copilot instruction files from the Claude sources.

Claude Code files are the source of truth. Copilot reads .claude/skills/ directly,
so skills need no copy.

  CLAUDE.md            -> .github/copilot-instructions.md
  .claude/rules/*.md   -> .github/instructions/*.instructions.md  (paths -> applyTo)
  .claude/agents/*.md  -> .github/agents/*.agent.md               (tools mapped, model dropped)

Markers in the sources:
  <!-- claude-only --> ... <!-- /claude-only -->   dropped from the Copilot copy
  <!-- copilot-only ... -->                        unwrapped in the Copilot copy
Other block-level HTML comments are dropped, as Claude Code does.

Usage:  python3 .claude/scripts/sync_copilot.py [PROJECT_ROOT] [--check]
  --check   write nothing; exit 1 if a generated file is missing, stale or orphaned.

Template layout: in the workflow-instructions repo the same files are stored without
the leading dot (claude/, github/, CLAUDE.template.md) so no AI tool loads them there.
The script detects that layout; generated content is identical either way.
Requires Python 3.8+, standard library only.
"""
import json
import re
import sys
from pathlib import Path

MARK = "Generated by .claude/scripts/sync_copilot.py"

TOOL_MAP = {
    "Read": "read", "Grep": "search", "Glob": "search", "LS": "search",
    "Edit": "edit", "MultiEdit": "edit", "Write": "edit", "NotebookEdit": "edit",
    "Bash": "execute", "WebFetch": "web", "WebSearch": "web",
    "Agent": "agent", "Task": "agent", "TodoWrite": "todo",
}


# --- frontmatter ---------------------------------------------------------------

def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        try:
            return json.loads(value)
        except ValueError:
            return value[1:-1]
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def parse_frontmatter(block):
    """Parse the simple YAML used in our frontmatter: scalars, folded/literal
    scalars, lists ("- x" or "[x, y]"). Nested mappings are skipped."""
    data, key, mode = {}, None, None
    for line in block.split("\n"):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        top = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if top:
            key, value = top.group(1), top.group(2).strip()
            if value in (">", ">-", "|", "|-"):
                data[key], mode = "", "text"
            elif value == "":
                data[key], mode = [], "list"
            elif value.startswith("[") and value.endswith("]"):
                data[key] = [unquote(v) for v in value[1:-1].split(",") if v.strip()]
                mode = None
            else:
                data[key], mode = unquote(value), None
        elif mode == "list" and line.strip().startswith("- ") and line.startswith(("  -", "- ")):
            data[key].append(unquote(line.strip()[2:]))
        elif mode == "text":
            data[key] = (data[key] + " " + line.strip()).strip()
        else:  # nested mapping (e.g. hooks): not needed for Copilot
            data[key], mode = None, "skip"
    return data


def split_frontmatter(text):
    match = re.match(r"---\n(.*?)\n---[ \t]*(\n|$)", text, re.S)
    if not match:
        return {}, text
    return parse_frontmatter(match.group(1)), text[match.end():]


def expand_braces(pattern):
    """'src/*.{ts,tsx}' -> ['src/*.ts', 'src/*.tsx'] (applyTo is comma-separated)."""
    match = re.search(r"\{([^{}]*,[^{}]*)\}", pattern)
    if not match:
        return [pattern]
    out = []
    for option in match.group(1).split(","):
        out += expand_braces(pattern[:match.start()] + option + pattern[match.end():])
    return out


# --- body ------------------------------------------------------------------------

def transform_body(text):
    out, in_fence, skip_depth, comment = [], False, 0, None
    for line in text.split("\n"):
        stripped = line.strip()
        if comment is not None:  # inside a multi-line HTML comment
            if "-->" in stripped:
                if comment == "copilot":
                    before = stripped.split("-->")[0].rstrip()
                    if before:
                        out.append(before)
                comment = None
            elif comment == "copilot":
                out.append(line)
            continue
        if stripped.startswith(("```", "~~~")):
            in_fence = not in_fence
        if not in_fence:
            if stripped == "<!-- claude-only -->":
                skip_depth += 1
                continue
            if stripped == "<!-- /claude-only -->":
                skip_depth = max(0, skip_depth - 1)
                continue
            if skip_depth:
                continue
            if stripped.startswith("<!-- copilot-only"):
                inner = stripped[len("<!-- copilot-only"):]
                if "-->" in inner:
                    if inner.split("-->")[0].strip():
                        out.append(inner.split("-->")[0].strip())
                else:
                    comment = "copilot"
                    if inner.strip():
                        out.append(inner.strip())
                continue
            if stripped.startswith("<!--"):
                if "-->" not in stripped:
                    comment = "drop"
                continue
        elif skip_depth:
            continue
        out.append(line)

    body = "\n".join(out)
    name = r"([^\s`'\"()\[\]/]+)"
    body = re.sub(r"\.claude/rules/" + name + r"\.md", r".github/instructions/\1.instructions.md", body)
    body = re.sub(r"\.claude/agents/" + name + r"\.md", r".github/agents/\1.agent.md", body)
    body = body.replace(".claude/rules/", ".github/instructions/")
    body = body.replace(".claude/agents/", ".github/agents/")
    body = re.sub(r"(?<![\w/.])CLAUDE\.md", ".github/copilot-instructions.md", body)
    body = re.sub(r"\n{3,}", "\n\n", body)
    return body.strip() + "\n"


def header(source):
    return f"<!-- {MARK} from {source} — edit the source, not this file. -->\n\n"


def render_instructions(text):
    return header("CLAUDE.md") + transform_body(text)


def render_rule(text, source):
    meta, body = split_frontmatter(text)
    paths = meta.get("paths") or ["**"]
    if isinstance(paths, str):
        paths = [p.strip() for p in paths.split(",")]
    globs = [g for p in paths for g in expand_braces(p)]
    return f"---\napplyTo: {json.dumps(','.join(globs))}\n---\n\n" + header(source) + transform_body(body)


def render_agent(text, source):
    meta, body = split_frontmatter(text)
    lines = ["---"]
    if meta.get("name"):
        lines.append(f"name: {meta['name']}")
    if meta.get("description"):
        lines.append(f"description: {json.dumps(meta['description'], ensure_ascii=False)}")
    tools = meta.get("tools")
    if tools:
        if isinstance(tools, str):
            tools = [t.strip() for t in tools.split(",")]
        mapped = []
        for tool in tools:
            name = TOOL_MAP.get(tool.split("(")[0].strip())
            if name and name not in mapped:
                mapped.append(name)
        lines.append(f"tools: {json.dumps(mapped)}")
    lines.append("---\n")
    return "\n".join(lines) + "\n" + header(source) + transform_body(body)


# --- main ------------------------------------------------------------------------

def layout(root):
    """(claude dir, github dir, CLAUDE.md file) for a project or the template store."""
    if (root / "claude").is_dir() and not (root / ".claude").is_dir():
        return root / "claude", root / "github", root / "CLAUDE.template.md"
    return root / ".claude", root / ".github", root / "CLAUDE.md"


def planned_outputs(root):
    claude, github, claude_md = layout(root)
    outputs = {}
    if claude_md.exists():
        outputs[github / "copilot-instructions.md"] = render_instructions(claude_md.read_text(encoding="utf-8"))
    for src in sorted((claude / "rules").glob("**/*.md")):
        rel = src.relative_to(claude / "rules")
        name = rel.with_suffix("").as_posix().replace("/", "-")
        outputs[github / f"instructions/{name}.instructions.md"] = render_rule(
            src.read_text(encoding="utf-8"), f".claude/rules/{rel.as_posix()}")
    for src in sorted((claude / "agents").glob("*.md")):
        outputs[github / f"agents/{src.stem}.agent.md"] = render_agent(
            src.read_text(encoding="utf-8"), f".claude/agents/{src.name}")
    return outputs


def orphans(root, outputs):
    _, github, _ = layout(root)
    found = []
    for folder, pattern in (("instructions", "*.instructions.md"), ("agents", "*.agent.md")):
        for path in sorted((github / folder).glob(pattern)):
            if path not in outputs and MARK in path.read_text(encoding="utf-8"):
                found.append(path)
    return found


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    root = Path(args[0]).resolve() if args else Path(__file__).resolve().parents[2]
    outputs = planned_outputs(root)
    stale = [p for p, content in outputs.items()
             if not p.exists() or p.read_text(encoding="utf-8") != content]
    extra = orphans(root, outputs)

    if check:
        for path in stale:
            print(f"out of date: {path.relative_to(root)}")
        for path in extra:
            print(f"orphaned:    {path.relative_to(root)}")
        if stale or extra:
            print("Run: python3 .claude/scripts/sync_copilot.py")
            return 1
        print(f"Copilot files are in sync ({len(outputs)} files).")
        return 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote    {path.relative_to(root)}")
    for path in extra:
        path.unlink()
        print(f"removed  {path.relative_to(root)}")
    if not stale and not extra:
        print(f"Copilot files are in sync ({len(outputs)} files).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
